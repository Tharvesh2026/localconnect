export function createSvgAvatar(
  initials: string,
  bgColor: string,
  textColor: string,
  iconChar: string
): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" width="120" height="120">
    <defs>
      <linearGradient id="grad-${bgColor.replace('#', '')}" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgColor}" />
        <stop offset="100%" stop-color="#1c1917" stop-opacity="0.8" />
      </linearGradient>
    </defs>
    <rect width="120" height="120" rx="60" fill="url(#grad-${bgColor.replace('#', '')})" />
    <circle cx="60" cy="60" r="54" fill="none" stroke="rgba(255,255,255,0.2)" stroke-width="3" />
    <text x="60" y="66" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif" font-size="34" font-weight="bold" fill="${textColor}" text-anchor="middle" dominant-baseline="middle">${initials}</text>
    <g transform="translate(74, 74)">
      <circle cx="16" cy="16" r="16" fill="#f59e0b" stroke="#ffffff" stroke-width="2" />
      <text x="16" y="21" font-size="14" text-anchor="middle">${iconChar}</text>
    </g>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

